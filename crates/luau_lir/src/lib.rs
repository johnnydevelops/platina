use std::fmt::Write;

use ir::*;

pub const PRELUDE: &str = include_str!("prelude.luau");

/// Max functions kept as module-level locals (Luau allows 200 locals per function scope,
/// and the prelude uses some). The rest live in the `FT` table.
const MAX_LOCAL_FUNCS: usize = 120;

struct ProgNames {
    local: Vec<bool>,
}
impl emit::Names for ProgNames {
    fn func(&self, id: u32) -> String {
        if self.local[id as usize] { format!("F{id}") } else { format!("FT[{id}]") }
    }
}

fn call_counts(p: &Program) -> Vec<usize> {
    let mut c = vec![0usize; p.funcs.len()];
    for f in &p.funcs {
        for b in &f.blocks {
            for s in &b.stmts {
                if let Stmt::Call { callee: Callee::Func(i), .. } = s {
                    c[*i as usize] += 1;
                }
            }
        }
    }
    c
}

/// Emit a whole program as a single Luau ModuleScript.
pub fn emit_program(p: &Program) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("--!native\n--!optimize 2\n--!nolint\n");
    out.push_str("-- Generated by Platina (https://github.com/johnnydevelops/platina). Do not edit.\n");
    writeln!(out, "local MEM: buffer = buffer.create({})", p.initial_mem).unwrap();
    writeln!(out, "local SP: number = {}", p.stack_top).unwrap();
    writeln!(out, "local HEAP_BASE: number = {}", p.heap_base).unwrap();
    let prelude_at = out.len();
    if !p.data.is_empty() {
        let escaped = emit::lua_string(&p.data);
        let b64 = emit::base64(&p.data);
        if b64.len() + 2 < escaped.len() {
            writeln!(out, "b64write({}, \"{}\")", p.data_base, b64).unwrap();
        } else {
            writeln!(out, "buffer.writestring(MEM, {}, {})", p.data_base, escaped).unwrap();
        }
    }
    // hottest functions become locals, the rest go through the FT table
    let counts = call_counts(p);
    let mut order: Vec<usize> = (0..p.funcs.len()).collect();
    order.sort_by_key(|i| std::cmp::Reverse(counts[*i]));
    let mut local = vec![false; p.funcs.len()];
    // module scope budget: 200 locals minus the prelude's and our own (MEM, SP, HEAP_BASE, FN, FT, ...)
    let prelude_locals: usize = PRELUDE
        .lines()
        .filter(|l| l.starts_with("local "))
        .map(|l| {
            let decl = l.trim_start_matches("local function ").trim_start_matches("local ");
            let names = decl.split(['=', '(']).next().unwrap_or("");
            names.split(',').count()
        })
        .sum();
    // leave room for the minifier's aliases and string table
    let budget = MAX_LOCAL_FUNCS.min(190usize.saturating_sub(prelude_locals + 8 + minify::MAX_ALIASES + 2));
    for i in order.into_iter().take(budget) {
        local[i] = true;
    }
    let names_cb = ProgNames { local: local.clone() };
    let names: Vec<String> = (0..p.funcs.len()).filter(|i| local[*i]).map(|i| format!("F{i}")).collect();
    for chunk in names.chunks(32) {
        writeln!(out, "local {}", chunk.join(", ")).unwrap();
    }
    if local.iter().any(|l| !l) {
        writeln!(out, "local FT = table.create({})", p.funcs.len()).unwrap();
    }
    writeln!(out, "local FN = table.create({})", p.table.len()).unwrap();
    for (i, f) in p.funcs.iter().enumerate() {
        if let Ok(filt) = std::env::var("LUAU_DUMP_LIR") {
            if f.name.contains(&filt) {
                eprintln!("=== LIR {}", f.name);
                for (bi, b) in f.blocks.iter().enumerate() {
                    if b.stmts.is_empty() && b.term == Term::Unreachable {
                        continue;
                    }
                    eprintln!("b{bi}:");
                    for s in &b.stmts {
                        eprintln!("    {s:?}");
                    }
                    eprintln!("    -> {:?}", b.term);
                }
            }
        }
        if std::env::var("LUAU_DUMP_LIR").is_ok_and(|filt| f.name.contains(&filt)) {
            let r: Vec<String> = f.vars.iter().enumerate().filter_map(|(i, v)| v.range.map(|r| format!("{i}:{:?}", r))).collect();
            eprintln!("ranges: {}", r.join(" "));
        }
        let st = structure::structure(f).map_err(|_| format!("irreducible control flow in {}", f.name))?;
        writeln!(out, "\n-- {}", f.name.replace('\n', " ")).unwrap();
        let e = emit::FnEmitter::new(f, &names_cb);
        let header = if local[i] { format!("function F{i}") } else { format!("FT[{i}] = function") };
        out.push_str(&e.emit(&st, &header));
    }
    for (slot, fid) in p.table.iter().enumerate() {
        if slot > 0 {
            writeln!(out, "FN[{slot}] = {}", emit::Names::func(&names_cb, *fid)).unwrap();
        }
    }
    out.push_str("\nreturn {\n");
    for (name, fid) in &p.exports {
        writeln!(out, "\t{name} = {},", emit::Names::func(&names_cb, *fid)).unwrap();
    }
    out.push_str("\tmemory = function(): buffer return MEM end,\n");
    out.push_str("}\n");
    let used = idents(&out);
    out.insert_str(prelude_at, &shaken_prelude(&used));
    Ok(out)
}

fn idents(s: &str) -> std::collections::HashSet<String> {
    let mut out = std::collections::HashSet::new();
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i].is_ascii_alphabetic() || b[i] == b'_' {
            let st = i;
            while i < b.len() && (b[i].is_ascii_alphanumeric() || b[i] == b'_') {
                i += 1;
            }
            out.insert(s[st..i].to_string());
        } else {
            i += 1;
        }
    }
    out
}

/// The prelude reduced to the items (top-level `local` definitions) that the generated code
/// references, directly or through other items.
fn shaken_prelude(used: &std::collections::HashSet<String>) -> String {
    // split into items: each starts at a top-level `local`
    let mut items: Vec<(Vec<String>, String)> = vec![];
    for line in PRELUDE.lines() {
        if line.starts_with("local ") {
            let decl = line.trim_start_matches("local function ").trim_start_matches("local ");
            let names = decl.split(['=', '(']).next().unwrap_or("");
            let defs: Vec<String> = names
                .split(',')
                .map(|n| n.split(':').next().unwrap_or("").trim().to_string())
                .filter(|n| !n.is_empty())
                .collect();
            items.push((defs, String::new()));
        } else if line.starts_with("--") || items.is_empty() {
            continue;
        }
        let it = items.last_mut().unwrap();
        it.1.push_str(line);
        it.1.push('\n');
    }
    let mut need: std::collections::HashSet<String> = used.clone();
    let mut keep = vec![false; items.len()];
    loop {
        let mut changed = false;
        for (k, (defs, text)) in items.iter().enumerate() {
            if !keep[k] && defs.iter().any(|d| need.contains(d)) {
                keep[k] = true;
                changed = true;
                need.extend(idents(text));
            }
        }
        if !changed {
            break;
        }
    }
    let mut out = String::new();
    for (k, (_, text)) in items.iter().enumerate() {
        if keep[k] {
            out.push_str(text);
        }
    }
    out
}
